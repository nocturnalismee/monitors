-- Real-time redesign F0: partitioning + multi-level rollup support.
--
-- 1) metrics_history gains bucket_seconds (rollup level 300/3600/86400).
--    UNIQUE key becomes (server_id, bucket_seconds, recorded_at) so each level
--    can carry its own bucket while keeping existing 300s behaviour unchanged
--    (new column defaults to 300).
-- 2) metrics becomes RANGE COLUMNS(recorded_at) partitioned per day so raw
--    retention can drop whole partitions (24h) instead of batch DELETE.
--    PRIMARY KEY becomes (id, recorded_at) because every unique key of a
--    partitioned table must include the partition column.
-- 3) MySQL/MariaDB do not allow foreign keys on partitioned InnoDB tables.
--    The two FKs involving `metrics` are therefore removed:
--      - fk_metrics_server (metrics.server_id -> servers.id): replaced by
--        explicit DELETE FROM metrics in the server-delete code paths.
--      - fk_service_metrics_metric (service_metrics.metric_id -> metrics.id):
--        metric_id becomes a plain column; service_metrics rows are purged by
--        retention on the same timeline as metrics, so no stale join matters.
--
-- NOTE FOR OPERATORS: this file was edited after its initial release to add the
-- `pmin` partition (holds any metrics recorded before 2026-08-01). On databases
-- where this migration was ALREADY applied, php migrate.php will report a
-- checksum mismatch for this file. Update the stored checksum to keep going:
--
--   UPDATE schema_migrations
--   SET checksum_sha256 = '<hash_file sha256 of this file>'
--   WHERE migration_name = '20260811_realtime_partitioning.sql';
--
-- Then (optionally) introduce pmin on those databases with:
--
--   ALTER TABLE metrics REORGANIZE PARTITION pXXXXXXX INTO (
--     PARTITION pmin VALUES LESS THAN ('2026-08-01'),
--     PARTITION pXXXXXXX VALUES LESS THAN ('2026-08-DD')
--   );
--
-- where pXXXXXXX is the first daily partition currently present.

ALTER TABLE metrics_history
  ADD COLUMN bucket_seconds INT NOT NULL DEFAULT 300 AFTER server_id,
  DROP INDEX idx_history_server_recorded,
  ADD UNIQUE INDEX idx_history_server_bucket_recorded (server_id, bucket_seconds, recorded_at);

ALTER TABLE service_metrics DROP FOREIGN KEY fk_service_metrics_metric;

ALTER TABLE metrics DROP FOREIGN KEY fk_metrics_server;

ALTER TABLE metrics
